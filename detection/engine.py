
from detection.brute_force import detect_brute_force
from detection.request_burst import detect_request_burst


def run_detection(log_file):
    """
    Run all detection rules and return a unified list of alerts.

    Args:
        log_file: Path to the JSONL security event log.

    Returns:
        List of alerts generated by all detection rules.
    """

    alerts = []

    # Run brute-force detection
    brute_force_alerts = detect_brute_force(log_file)
    alerts.extend(brute_force_alerts)

    # Run request-burst detection
    request_burst_alerts = detect_request_burst(log_file)
    alerts.extend(request_burst_alerts)

    return alerts
